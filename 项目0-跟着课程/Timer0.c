#include <REGX52.H> //c52库


//1毫秒触发一次的定时器，让他触发就自加，触发多少次就是多少毫秒
//由stc-isp-15xx-v6.75.exe自动生成初始化配置
void Timer0Init(void)		//1毫秒@12.000MHz
{
	TMOD &= 0xF0;		//设置定时器模式
	TMOD |= 0x01;		//设置定时器模式
	TL0 = 0x18;		//设置定时初值
	TH0 = 0xFC;		//设置定时初值
	TF0 = 0;		//清除TF0标志
	TR0 = 1;		//定时器0开始计时
	ET0=1;  //允许中断（没做解释，自行了解）
	EA=1;   //允许总中断
	PT0=0;   //中断优先级等于0
}

